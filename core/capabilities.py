    def _init_doc_layer(self):
        """Python-docx, Python-pptx, ReportLab"""
        import docx
        import pptx
        from reportlab.pdfgen import canvas
        
        class DocLayer:
            def create_word_doc(self, filename, content):
                doc = docx.Document()
                doc.add_paragraph(content)
                doc.save(filename)
                return f"Word doc saved to {filename}"
                
            def create_ppt(self, filename, title, slides_content):
                prs = pptx.Presentation()
                
                # 1. Title Slide
                title_slide_layout = prs.slide_layouts[0]
                slide = prs.slides.add_slide(title_slide_layout)
                slide.shapes.title.text = title
                slide.placeholders[1].text = "Generated by Omniagent v2.5 | Horizon Stack"

                # 2. Content Slides
                bullet_slide_layout = prs.slide_layouts[1] # Title and Content
                
                for slide_data in slides_content:
                    if isinstance(slide_data, str):
                        # Simple string case
                        s = prs.slides.add_slide(bullet_slide_layout)
                        s.shapes.title.text = "Info"
                        s.placeholders[1].text = slide_data
                    elif isinstance(slide_data, dict):
                        # Structured dict case
                        s = prs.slides.add_slide(bullet_slide_layout)
                        s.shapes.title.text = slide_data.get('slide_title', slide_data.get('title', 'Untitled'))
                        
                        # Handle body text or bullet points
                        tf = s.placeholders[1].text_frame
                        tf.text = slide_data.get('text', '')
                        
                        bullets = slide_data.get('bullet_points', [])
                        if bullets:
                            if not tf.text: tf.text = bullets[0]
                            else: 
                                p = tf.add_paragraph()
                                p.text = bullets[0]
                                
                            for b in bullets[1:]:
                                p = tf.add_paragraph()
                                p.text = b

                prs.save(filename)
                return f"Presentation saved to {filename} with {len(prs.slides)} slides."
        
        return DocLayer()

    def _init_knowledge_layer(self):
        """LangChain, LlamaIndex, FAISS, Transformers"""
        # We import these HEAVY libs only here
        from llama_index.core import VectorStoreIndex, SimpleDirectoryReader
        import faiss
        
        class KnowledgeLayer:
            def index_folder(self, folder_path):
                documents = SimpleDirectoryReader(folder_path).load_data()
