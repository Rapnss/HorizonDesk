
import importlib
import sys
import threading

class CapabilityManager:
    _instance = None
    _lock = threading.Lock()
    
    def __new__(cls):
        with cls._lock:
            if cls._instance is None:
                cls._instance = super(CapabilityManager, cls).__new__(cls)
                cls._instance.layers = {}
                cls._instance.loaded_libs = set()
        return cls._instance

    def load_layer(self, layer_name):
        """Lazy load a capability layer."""
        if layer_name in self.layers:
            return self.layers[layer_name]
        
        print(f"[CapabilityManager] Loading Layer: {layer_name}...")
        
        try:
            if layer_name == "DataLayer":
                self.layers[layer_name] = self._init_data_layer()
            elif layer_name == "DocLayer":
                self.layers[layer_name] = self._init_doc_layer()
            elif layer_name == "KnowledgeLayer":
                self.layers[layer_name] = self._init_knowledge_layer()
            elif layer_name == "AutomationLayer":
                self.layers[layer_name] = self._init_automation_layer()
            elif layer_name == "VisionLayer":
                self.layers[layer_name] = self._init_vision_layer()
            else:
                raise ValueError(f"Unknown layer: {layer_name}")
            
            print(f"[CapabilityManager] Layer {layer_name} READY.")
            return self.layers[layer_name]
        except ImportError as e:
            print(f"[CapabilityManager] FAILED to load {layer_name}: {e}")
            return None
        except Exception as e:
            print(f"[CapabilityManager] Error loading {layer_name}: {e}")
            return None

